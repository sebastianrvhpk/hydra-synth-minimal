import { mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

const readArg = (name, fallback = undefined) => {
  const prefix = `--${name}=`
  const match = process.argv.slice(2).find((arg) => arg.startsWith(prefix))
  return match ? match.slice(prefix.length) : fallback
}

const xmur3 = (seedText) => {
  let hash = 1779033703 ^ seedText.length
  for (let index = 0; index < seedText.length; index += 1) {
    hash = Math.imul(hash ^ seedText.charCodeAt(index), 3432918353)
    hash = (hash << 13) | (hash >>> 19)
  }
  return () => {
    hash = Math.imul(hash ^ (hash >>> 16), 2246822507)
    hash = Math.imul(hash ^ (hash >>> 13), 3266489909)
    return (hash ^= hash >>> 16) >>> 0
  }
}

const mulberry32 = (seed) => () => {
  let value = seed += 0x6D2B79F5
  value = Math.imul(value ^ (value >>> 15), value | 1)
  value ^= value + Math.imul(value ^ (value >>> 7), value | 61)
  return ((value ^ (value >>> 14)) >>> 0) / 4294967296
}

const seedText = readArg('seed', String(Date.now()))
const seed = xmur3(seedText)()
const random = mulberry32(seed)

const rn = (max = 1) => random() * max
const btw = (min, max) => min + random() * (max - min)
const intgr = (min, max) => min + Math.floor(random() * (max - min + 1))
const pick = (values) => values[Math.floor(random() * values.length)]
const maybe = (p = 0.5) => random() < p

const fmt = (value, digits = 5) => {
  if (Number.isInteger(value)) return String(value)
  const fixed = Number(value).toFixed(digits)
  return fixed
    .replace(/0+$/u, '')
    .replace(/\.$/u, '')
    .replace(/^-0$/u, '0')
    .replace(/^0\./u, '.')
    .replace(/^-0\./u, '-.')
}

const helperBlock = `// Generated by scripts/hydra-style-generate.mjs
// Seed: ${seedText}
// Standalone helper vocabulary copied from the curated Hydra style grammar.
const TAU = Math.PI * 2;
const A = width > height ? height / width : 1;
const B = height > width ? width / height : 1;
const rn = (max = 1) => Math.random() * max;
const btw = (min = 0, max = 1, power = 1) =>
  min + Math.random() ** power * (max - min);
const intgr = (min = 0, max = 1, power = 1) => {
  const lo = Math.ceil(min);
  const hi = Math.floor(max);
  return lo + Math.floor(Math.random() ** power * (hi - lo + 1));
};
const bi = (p = 0.5) => rn() > p ? 1 : -1;
const bl = (p = 0.5, power = 1) => Math.random() ** power > p ? 1 : 0;
const ns = (freq = 3, vel = 0, x = rn(), y = rn()) =>
  noise(freq, vel).modulate(solid(width * x, height * y), 1).scale(1, A, B);
`

const shapeMaskLattice = () => {
  const speed = fmt(pick([0.5, 0.75, 1, 1.5, 2]))
  const base = fmt(pick([0.5, 0.375, 0.25]))
  const drift = `${intgr(1, 3)} / width`
  const feedbackBlend = fmt(btw(0.5, 0.9), 4)
  const thresholds = [fmt(btw(-0.3, 0.25)), fmt(btw(-0.15, 0.4)), fmt(btw(0, 0.55)), fmt(btw(0.15, 0.75))]

  return `speed = ${speed};

shape(4, 1, 0)
.scale(${base}, 1, 1, rn(), rn())
.repeat(width / ${intgr(2, 5)}, height / ${intgr(2, 5)}, rn(), rn())
.mult(ns(${fmt(btw(0.5, 1.5))}, ${fmt(btw(0.05, 0.2))}).thresh(${thresholds[0]}, .25))
.diff(shape(4, 1, 0).scale(.25, 1, 1, rn(), rn()).repeat(width / 4, height / 4, rn(), rn()).mult(ns(${fmt(btw(1, 2))}, ${fmt(btw(0.05, 0.25))}).thresh(${thresholds[1]}, .25)))
.diff(shape(4, 1, 0).scale(.125, 1, 1, rn(), rn()).repeat(width / 8, height / 8, rn(), rn()).mult(ns(${fmt(btw(0.3, 1))}, ${fmt(btw(0.05, 0.2))}).thresh(${thresholds[2]}, .25)))
.diff(shape(4, 1, 0).scale(.5, 1, 1, rn(), rn()).rotate(0, ${fmt(btw(0.01, 0.2))}).repeat(width / 2, height / 2, rn(), rn()).mult(ns(${fmt(btw(1.25, 2))}, ${fmt(btw(0.05, 0.2))}).thresh(${thresholds[3]}, .25)))
.diff(src(o0).mask(ns(TAU, ${fmt(btw(0.2, 2))}).thresh(0, 0).pixelate(${maybe() ? 'width, 1' : '1, height'})))
.blend(src(o0).modulate(solid(1 / width, 1 / height).mult(osc(TAU, .1).brightness(-.5).contrast(2)), -1), ${feedbackBlend})
.scrollX(-${drift})
.blend(o0, ${fmt(btw(0.35, 0.75), 4)})
.out();

render(o0);`
}

const feedbackKaleid = () => {
  const hue = fmt(btw(0.5, 3), 4)
  const displacement = fmt(btw(1.5, 3.5), 4)
  const symmetry = intgr(300, 900)
  const colorama = fmt(btw(0.0002, 0.003), 5)
  const maskThreshold = fmt(btw(0.5, 0.9), 4)

  return `dx = rn(), dy = rn();

src(o0)
.layer(solid()
  .add(osc(Math.PI * .6, ${fmt(btw(0.05, 0.75))}, 1).modulate(solid(dx * width, 0), 1).pixelate(1, 1), 1)
  .add(osc(Math.PI * .2, ${fmt(btw(0.05, 0.75))}, 1).modulate(solid(dx * width, 0), 1).kaleid(${symmetry}), .5)
  .add(osc(Math.PI * 6, ${fmt(btw(0.05, 0.75))}, 1).modulate(solid(dy * width, 0), 1).pixelate(1, 1), -.25)
  .add(osc(TAU, ${fmt(btw(0.05, 0.75))}, 1).modulate(solid(dy * width, 0), 1).kaleid(${symmetry}), -.25)
  .mask(shape(4, .001, 0).rotate(0, Math.PI / 4 / 1.5).scale(1, A, B)
    .modulateScale(ns(4.5, 0).pixelate(8, 1).scrollX(0, 1).pixelate(1, 1).brightness(1), ${intgr(180, 520)})
    .mask(ns(4.5, 0).pixelate(8, 1).thresh(-.5, 0).scrollX(0, ${fmt(btw(1, 2))}).pixelate(1, 1))
    .mask(ns(.7, -2).thresh(0, 0))))
.modulateRotate(ns(.3, .25), Math.PI / 360 * ${fmt(btw(0.5, 2.5))})
.modulate(ns(.3, .25).color(.05, 1).add(ns(${fmt(btw(0.3, 1.25))}, ${fmt(btw(0.25, 1.5))}).color(1, .05)).color(1 / width, 1 / height), ${displacement})
.modulateHue(o0, ${hue})
.diff(solid())
.layer(src(o0).colorama(${colorama}).mask(ns(.3, 1).thresh(${maskThreshold}, 0)))
.out();

src(o0).b().blend(src(o0).r(), () => Math.sin(time) / 2 + .5).contrast(2).out(o1);

src(o2)
.modulate(gradient().scale(.5, A).brightness(-.5).color(2 / width, 2 / height), -2)
.layer(solid().layer(src(o1).blend(o0, .5)).mask(shape(4, 1, 0).scale(.5, A).scale(() => -time / 4 % 1)))
.out(o2);

render(o2);`
}

const rgbScanline = () => {
  const cell = pick([4, 6, 8])
  const grid = intgr(4, 12)
  const amount = fmt(btw(4, 18), 4)
  const feedback = fmt(btw(0.25, 0.75), 4)
  const threshold = fmt(btw(0.05, 0.35), 4)

  return `speed = ${fmt(btw(0.2, 1.5), 4)};

shape(4, 1, 0).scale(.25, 1, 1, 0, 0).repeat(width / ${cell}, height / ${cell}).color(1, 0, 0)
.add(shape(4, 1, 0).scale(.25, 1, 1, 0, 0).repeat(width / ${cell}, height / ${cell}).color(0, 1, 0)
  .modulate(ns(${fmt(btw(2, 8))}, ${fmt(btw(0.1, 1))}).color(1 / width, 0).add(ns(${fmt(btw(8, 18))}, ${fmt(btw(-0.5, -0.05))}).color(0, 1 / height)).pixelate(1, 1)
    .mask(ns(${fmt(btw(12, 28))}, ${fmt(btw(-0.2, -0.02))}).pixelate(1, height).thresh(${threshold}, 0)), ${amount}))
.add(shape(4, 1, 0).scale(.25, 1, 1, 0, 0).repeat(width / ${cell}, height / ${cell}).color(0, 0, 1)
  .modulate(ns(${fmt(btw(2, 8))}, ${fmt(btw(-1, -0.1))}).color(0, 1 / height).add(ns(${fmt(btw(8, 18))}, ${fmt(btw(0.05, 0.5))}).color(1 / width, 0)).pixelate(1, 1)
    .mask(ns(${fmt(btw(12, 28))}, ${fmt(btw(0.02, 0.2))}).pixelate(width, 1).thresh(${fmt(btw(0.1, 0.4))}, 0)), ${fmt(btw(6, 18))}))
.add(o0, ${fmt(btw(0.35, 0.75), 4)})
.blend(o0, ${feedback})
.modulate(solid()
  .add(ns(${fmt(btw(8, 35))}, ${fmt(btw(0.05, 0.5))}).color(1 / width, 0), 1)
  .add(ns(${fmt(btw(8, 35))}, ${fmt(btw(0.05, 0.5))}).color(0, 1 / height), 1)
  .pixelate(${grid} / A, ${grid} / B), ${fmt(btw(1, 5), 4)})
.out();

src(o1)
.modulate(solid(1 / width, 0).add(ns(${fmt(btw(12, 35))}, ${fmt(btw(0.02, 0.2))}).thresh(.05, .1)).pixelate(1, ${grid} / B), btw(-2, 2) * 2)
.layer(src(o0).scroll(rn(), rn(), btw(-3, 3) / width, btw(-3, 3) / height)
  .mask(shape(4, 1, 0).scale(1, btw(2, 4) / width, 1, bl()).scrollX(btw(-2, 2) / width)))
.out(o1);

solid().diff(src(o1)).out(o2);
render(o2);`
}

const generators = {
  'shape-mask-lattice': shapeMaskLattice,
  'feedback-kaleid': feedbackKaleid,
  'rgb-scanline': rgbScanline
}

const archetype = readArg('archetype', pick(Object.keys(generators)))
if (!generators[archetype]) {
  throw new Error(`Unknown archetype: ${archetype}. Expected one of: ${Object.keys(generators).join(', ')}`)
}

const outDir = path.resolve(readArg('outDir', path.join(repoRoot, '.tmp', 'hydra-style', 'generated')))
mkdirSync(outDir, { recursive: true })

const outputPath = path.join(outDir, `${archetype}_${seedText.replace(/[^A-Za-z0-9_-]+/gu, '_')}.js`)
const code = `${helperBlock}\n${generators[archetype]()}\n`
writeFileSync(outputPath, code)

console.log(`Generated ${archetype} patch`)
console.log(`Seed: ${seedText}`)
console.log(`Output: ${outputPath}`)
